import postgres from 'postgres';
import fs from 'fs';

// Connection URL from CLI argument or env var
let connStr = process.argv[2] || process.env.DATABASE_URL;
if (!connStr && fs.existsSync('.env.local')) {
  const envContent = fs.readFileSync('.env.local', 'utf8');
  for (const line of envContent.split('\n')) {
    if (line.startsWith('DATABASE_URL=')) {
      connStr = line.substring('DATABASE_URL='.length).trim();
      if ((connStr.startsWith('"') && connStr.endsWith('"')) || (connStr.startsWith("'") && connStr.endsWith("'"))) {
        connStr = connStr.slice(1, -1);
      }
    }
  }
}

const isMain = Boolean(process.argv[1]?.includes('sync-october-schedule'));
if (isMain && !connStr) {
  console.error('DATABASE_URL is required. Provide it as an argument or set DATABASE_URL in .env.local.');
  process.exit(1);
}
