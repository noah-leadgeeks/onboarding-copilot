async function syncOctoberToRemote() {
  const sql = postgres(validConnStr, { ssl: 'require' });

  console.log('1. Connecting to remote database:', validConnStr.replace(/:[^:@]+@/, ':***@'));

  // Move Month 2 Review and Month 3 Review rows to follow cleanly at 102 and 106 if they currently occupy row 81 or 85
  console.log('2. Shifting Month 2 and Month 3 Reviews if needed...');
  await sql`
    UPDATE activities
    SET row_number = 102, id = 'sched-row-102'
    WHERE id = 'sched-row-81' OR (topic LIKE '%Month 2 Performance Review%' AND row_number = 81)
  `;
  await sql`
    UPDATE activities
    SET row_number = 106, id = 'sched-row-106'
    WHERE id = 'sched-row-85' OR (topic LIKE '%Month 3 Performance Review%' AND row_number = 85)
  `;

  console.log(`3. Upserting ${OCTOBER_ACTIVITIES.length} October activities into activities table...`);
  for (const act of OCTOBER_ACTIVITIES) {
    await sql`
      INSERT INTO activities (
        id,
        row_number,
        week,
        day,
        date,
        activity_count,
        pic,
        topic,
        main_media,
        duration_minutes,
        start_time,
        end_time,
        progress,
        materials_link,
        notes,
        created_at,
        updated_at
      ) VALUES (
        ${act.id},
        ${act.rowNumber},
        ${act.week},
        ${act.day},
        ${act.date},
        ${act.activityCount},
        ${act.pic},
        ${act.topic},
        ${act.mainMedia},
        ${act.durationMinutes},
        ${act.startTime},
        ${act.endTime},
        ${act.progress},
        ${act.materialsLink || ''},
        ${act.notes},
        ${new Date().toISOString()},
        ${new Date().toISOString()}
      )
      ON CONFLICT (id) DO UPDATE SET
        row_number = EXCLUDED.row_number,
        week = EXCLUDED.week,
        day = EXCLUDED.day,
        date = EXCLUDED.date,
        activity_count = EXCLUDED.activity_count,
        pic = EXCLUDED.pic,
        topic = EXCLUDED.topic,
        main_media = EXCLUDED.main_media,
        duration_minutes = EXCLUDED.duration_minutes,
        start_time = EXCLUDED.start_time,
        end_time = EXCLUDED.end_time,
        progress = EXCLUDED.progress,
        materials_link = EXCLUDED.materials_link,
        notes = EXCLUDED.notes,
        updated_at = EXCLUDED.updated_at;
    `;
  }

  console.log('4. Verifying synced October activities in remote database...');
  const countRes = await sql`SELECT count(*) FROM activities`;
  console.log(`Total activities in remote DB: ${countRes[0].count}`);

  const sample = await sql`
    SELECT row_number, day, date, topic, duration_minutes, start_time, end_time, progress, notes
    FROM activities
    WHERE row_number >= 58
    ORDER BY row_number ASC
  `;
  for (const r of sample) {
    const t = (r.topic || '').split('\n')[0];
    console.log(`Row ${r.row_number} | ${r.day} ${r.date} | ${t.substring(0, 35)}... | ${r.start_time}-${r.end_time} (${r.duration_minutes}m) | ${r.progress} | ${r.notes}`);
  }

  await sql.end();
  console.log('October activities sync completed successfully!');
}

